#!/bin/zsh
# Правка json-файла на месте, устойчивая к пустому файлу и к гонке писателей.
#
# Гоча, из-за которой питомец засыпал посреди работы: `jq '. + {…}' f > f.tmp`
# на ПУСТОМ файле даёт пустой вывод и код 0, поэтому `mv` затирал файл нулём.
# Починить его потом было нечем — все правки шли тем же приёмом, и сессия
# навсегда выпадала из сводки. Второй источник пустоты — гонка: статуслайн и
# хуки правят один файл, и оба писали в один и тот же `f.tmp`.
#
# Здесь: пустой или битый вход читается как {}, пустой вывод в файл не заезжает,
# промежуточный файл у каждого писателя свой, а чтение-правка-запись идёт под
# блокировкой (shlock; flock на маке нет).
petjq() {
  local f=$1; shift
  local base out tmp="$f.new.$$" lock="$f.lock" i=0
  while (( i < 20 )); do
    /usr/bin/shlock -f "$lock" -p $$ 2>/dev/null && break
    sleep 0.05; (( i++ ))
  done
  base=$(/usr/bin/jq -c . "$f" 2>/dev/null) || base='{}'
  [[ -n $base ]] || base='{}'
  if out=$(print -r -- "$base" | /usr/bin/jq "$@" 2>/dev/null) && [[ -n $out ]]; then
    print -r -- "$out" > "$tmp" && mv -f "$tmp" "$f"
  fi
  rm -f "$tmp" "$lock"
  [[ -s $f ]]
}
