#!/bin/zsh
# Пишет, чем агент занят прямо сейчас: имя инструмента в файл своей сессии.
# Питомец показывает по нему значок. PostToolUse затирает пустым.
source "${0:h}/pet-lib.sh"
D="$HOME/.claude/.pet"
j=$(cat 2>/dev/null)
sid=$(print -r -- "$j" | /usr/bin/jq -r '.session_id // empty' 2>/dev/null)
[[ -n $sid ]] || exit 0
tool=${1:-}
[[ $tool == auto ]] && tool=$(print -r -- "$j" | /usr/bin/jq -r '.tool_name // empty' 2>/dev/null)

f="$D/$sid.json"
dir=$(print -r -- "$j" | /usr/bin/jq -r '.cwd // empty' 2>/dev/null)
# Файла может не быть (сессия поднята из --resume, файл вычищен как нулевой).
# Вызов инструмента сам по себе значит «агент работает» — заводим запись, иначе
# сессия не попадёт в сводку до следующего промпта.
if [[ ! -f $f ]]; then
  mkdir -p "$D"
  petjq "$f" --arg d "${dir:t}" --argjson ts "$(date +%s)" \
    '. + {state:"work", dir:$d, ts:$ts, since:$ts}'
fi
# Заодно подтверждаем, что сессия жива: ts ставится один раз на промпт, а
# работа над одной задачей идёт и 40 минут. Сводка отбрасывает записи старше
# 30 минут, поэтому питомец засыпал посреди работы («когда ты работал, он спал»).
# Каждый вызов инструмента — доказательство активности, им и двигаем ts.
# since НЕ трогаем: по нему видно, сколько агент занят этой задачей.
petjq "$f" --arg t "$tool" --argjson ts "$(date +%s)" '. + {tool:$t, ts:$ts}'

# Пересчитываем сводку: во время работы состояние не меняется, а питомец
# читает только .pet-state.json — без этого он засыпал бы на 30-й минуте.
"${0:h}/pet-roll.sh"
exit 0
